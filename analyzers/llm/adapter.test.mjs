import { mkdtempSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { buildChangeText, excerpt, onChange, reviewable, runTool, severityOf, systemPrompt } from './adapter.mjs';

describe('llm analyzer', () => {
  it('marks changed lines and merges nearby ranges', () => {
    const lines = Array.from({ length: 30 }, (_, i) => `l${i + 1}`);
    const out = excerpt(lines, [[10, 10], [14, 14]], 2);
    expect(out.split('\n')).toHaveLength(9); // 8..16
    expect(out).toContain('+   10| l10');
    expect(out).toContain('    11| l11');
    expect(out).not.toContain('...');
  });

  it('skips lock files, bundles and generated code, but not migrations', () => {
    expect(reviewable('package-lock.json')).toBe(false);
    expect(reviewable('web/app.min.js')).toBe(false);
    expect(reviewable('src/gen.ts', '// @generated by protoc')).toBe(false);
    expect(reviewable('db/migrations/0001.sql', '-- @generated')).toBe(true);
    expect(reviewable('src/a.ts', 'export const a = 1')).toBe(true);
  });

  it('lets a model finding be high (blocking) only at confidence >= 0.8', () => {
    expect(severityOf({ severity: 'high', confidence: 0.8 })).toBe('high');
    expect(severityOf({ severity: 'high', confidence: 0.79 })).toBe('medium');
    expect(severityOf({ severity: 'high' })).toBe('medium');
    expect(severityOf({ severity: 'high', confidence: 'very' })).toBe('medium');
    expect(severityOf({ severity: 'low', confidence: 0.1 })).toBe('low');
    expect(severityOf({ severity: 'critical', confidence: 1 })).toBe('medium');
  });

  it('keeps findings on changed lines only', () => {
    expect(onChange([[3, 5]], 4)).toBe(true);
    expect(onChange([[3, 5]], 6)).toBe(false);
    expect(onChange('all', 99)).toBe(true);
  });

  it('never reads outside the repository', () => {
    const root = mkdtempSync(join(tmpdir(), 'mcr-llm-'));
    writeFileSync(join(root, 'a.txt'), 'one\ntwo\n');
    expect(runTool(root, 'read_file', { path: 'a.txt' })).toContain('2| two');
    expect(runTool(root, 'read_file', { path: '../../etc/passwd' })).toMatch(/not found in the repository/);
    expect(runTool(root, 'grep', { pattern: 'two' })).toContain('a.txt:2');
  });

  it('does not follow a symlink out of the repository', () => {
    const outside = mkdtempSync(join(tmpdir(), 'mcr-secret-'));
    writeFileSync(join(outside, 'key'), 'sk-secret');
    const root = mkdtempSync(join(tmpdir(), 'mcr-llm-'));
    symlinkSync(join(outside, 'key'), join(root, 'key'));
    symlinkSync(outside, join(root, 'dir'));
    expect(runTool(root, 'read_file', { path: 'key' })).toMatch(/not found in the repository/);
    expect(runTool(root, 'list_dir', { path: 'dir' })).toMatch(/not found in the repository/);
    expect(runTool(root, 'grep', { pattern: 'sk-', path: 'dir' })).toMatch(/not found in the repository/);
  });

  it('greps plain text, so a pattern cannot hang the analyzer', () => {
    const root = mkdtempSync(join(tmpdir(), 'mcr-llm-'));
    writeFileSync(join(root, 'a.txt'), `${'a'.repeat(40)}!\nx(a+)+y\n`);
    expect(runTool(root, 'grep', { pattern: '(a+)+$' })).toBe('no matches');
    expect(runTool(root, 'grep', { pattern: '(A+)+Y' })).toContain('a.txt:2');
  });

  it('builds the prompt from changed files and states what not to flag', () => {
    const files = { 'a.ts': 'const a = 1;\nconst b = 2;\n', 'yarn.lock': 'x' };
    const { text } = buildChangeText('/r', ['a.ts', 'yarn.lock'], { 'a.ts': [[2, 2]] }, (_r, f) => files[f]);
    expect(text).toContain('=== a.ts');
    expect(text).not.toContain('yarn.lock');
    expect(systemPrompt('security', '')).toContain('Do NOT flag');
  });
});

describe('llm analyzer budget', () => {
  it('never spends the prompt on logs or tool output', () => {
    expect(reviewable('.playwright-mcp/console-1.log')).toBe(false);
    expect(reviewable('coverage/lcov-report/index.html')).toBe(false);
  });
});
